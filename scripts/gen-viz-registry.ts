/**
 * Auto-discovers visualization modules so a module branch never edits a shared file.
 * Every folder src/components/viz/<module>/ with an index.ts exporting `viz` is included.
 * Folders starting with "_" (shared code) and "__generated__" are skipped.
 * Output (git-ignored): src/components/viz/__generated__/registry.ts
 */
import fs from "node:fs"
import path from "node:path"

const VIZ_DIR = path.join(process.cwd(), "src", "components", "viz")
const OUT_DIR = path.join(VIZ_DIR, "__generated__")

const modules = fs
  .readdirSync(VIZ_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
  .filter((d) =>
    ["index.ts", "index.tsx"].some((f) => fs.existsSync(path.join(VIZ_DIR, d.name, f))),
  )
  .map((d) => d.name)
  .sort()

// Fail fast on duplicate component names across modules (would silently shadow in MDX).
const seen = new Map<string, string>()
for (const m of modules) {
  const file = ["index.ts", "index.tsx"]
    .map((f) => path.join(VIZ_DIR, m, f))
    .find((f) => fs.existsSync(f))!
  const body = /export const viz = \{([^}]*)\}/.exec(fs.readFileSync(file, "utf8"))?.[1]
  if (body === undefined) throw new Error(`${file} must contain: export const viz = { ... }`)
  for (const name of body
    .split(",")
    .map((s) => s.trim().split(":")[0]!.trim())
    .filter(Boolean)) {
    if (seen.has(name))
      throw new Error(`Viz "${name}" is exported by both ${seen.get(name)} and ${m}`)
    seen.set(name, m)
  }
}

const ident = (m: string) => `m_${m.replace(/[^a-zA-Z0-9]/g, "_")}`
const source = `// AUTO-GENERATED by scripts/gen-viz-registry.ts — do not edit.
${modules.map((m) => `import { viz as ${ident(m)} } from "../${m}"`).join("\n")}

export const vizComponents = {
${modules.map((m) => `  ...${ident(m)},`).join("\n")}
}
`

fs.mkdirSync(OUT_DIR, { recursive: true })
const out = path.join(OUT_DIR, "registry.ts")
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== source) fs.writeFileSync(out, source)
console.log(`✓ viz registry: ${modules.length} module(s), ${seen.size} component(s)`)
